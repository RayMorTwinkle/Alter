export type Locale = "hant" | "hans";
export const strings: Record<Locale, Strings> = { hant, hans };

export function defaultLocale(): Locale {
  try {
    const saved = localStorage.getItem("alter.locale");
    if (saved === "hant" || saved === "hans") return saved;
  } catch { /* storage unavailable */ }
  return /^zh-(TW|HK|MO|Hant)/i.test(navigator.language) ? "hant" : "hans";
}
